let lang = 'en';
const listeners = new Set();

export function getLang() {
  return lang;
}

export function initLang() {
  let saved = null;
  try {
    saved = localStorage.getItem('g99_lang');
  } catch {
    /* storage unavailable */
  }
  const nav = (navigator.language || 'en').toLowerCase();
  setLang(saved || (nav.startsWith('bn') ? 'bn' : 'en'), false);
}

export function setLang(l, persist = true) {
  lang = DICT[l] ? l : 'en';
  document.documentElement.lang = lang;
  if (persist) {
    try {
      localStorage.setItem('g99_lang', lang);
    } catch {
      /* ignore */
    }
  }
  applyI18n(document);
  listeners.forEach((fn) => fn(lang));
}

export function onLangChange(fn) {
  listeners.add(fn);
}

export function t(key, vars) {
  let s = (DICT[lang] && DICT[lang][key]) || DICT.en[key] || key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
  return s;
}

export function errText(code) {
  const k = `err.${code}`;
  return DICT[lang][k] || DICT.en[k] || t('err.internal_error');
}

/** Translate every element carrying a data-i18n* attribute under `root`. */
export function applyI18n(root) {
  root.querySelectorAll('[data-i18n]').forEach((el) => {
    el.textContent = t(el.dataset.i18n);
  });
  root.querySelectorAll('[data-i18n-placeholder]').forEach((el) => el.setAttribute('placeholder', t(el.dataset.i18nPlaceholder)));
  root.querySelectorAll('[data-i18n-title]').forEach((el) => el.setAttribute('title', t(el.dataset.i18nTitle)));
  root.querySelectorAll('[data-i18n-aria]').forEach((el) => el.setAttribute('aria-label', t(el.dataset.i18nAria)));
  document.title = t('app.title');
}
